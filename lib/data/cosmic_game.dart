import 'dart:math';

enum CosmicType { galaxia, buracoNegro, planeta, quasar }

extension CosmicTypeLabel on CosmicType {
  String get label {
    switch (this) {
      case CosmicType.galaxia: return 'Galáxia';
      case CosmicType.buracoNegro: return 'Buraco negro';
      case CosmicType.planeta: return 'Planeta';
      case CosmicType.quasar: return 'Quasar';
    }
  }
}

class CosmicChallenge {
  final String imageUrl;
  final CosmicType answer;
  const CosmicChallenge(this.imageUrl, this.answer);
}

